import type { EntryWizardState } from './state';
import { ENTRY_DEFAULT_WS_PATH, ENTRY_DEFAULT_ADMIN_LISTEN } from './state';
import { emitObject, prune } from '../../util/yamlEmit';
import type { YamlValue } from '../../util/yamlEmit';

export function buildEntryConfigYaml(state: EntryWizardState): string {
  const tun: Record<string, YamlValue> = {
    name: state.tunName.trim(),
    mtu: state.tunMtu,
    address: state.tunAddress.trim(),
  };
  if (state.tunIPv6Enabled && state.tunAddress6.trim()) {
    tun.address6 = state.tunAddress6.trim();
  }

  const socks5: Record<string, YamlValue> = {
    server: state.socks5Server.trim(),
  };
  if (state.socks5AuthEnabled) {
    if (state.socks5Username.trim()) socks5.username = state.socks5Username.trim();
    if (state.socks5Password) socks5.password = state.socks5Password;
  }
  if (state.socks5Transport === 'websocket') {
    socks5.transport = 'websocket';
    if (state.socks5WSPath.trim() && state.socks5WSPath.trim() !== ENTRY_DEFAULT_WS_PATH) {
      socks5.ws_path = state.socks5WSPath.trim();
    }
  }

  // Route/host state rides the existing SOCKS5 connection's route-watch
  // stream — no separate dashboard URL or bearer token is needed. The Muti Metroo
  // Entry autoroutes config has a single knob: `enabled`.
  const autoroutes: Record<string, YamlValue> = {};
  if (state.autoroutesEnabled) {
    autoroutes.enabled = true;
  }

  const logging: Record<string, YamlValue> = {};
  if (state.logLevel !== 'info') logging.level = state.logLevel;
  if (state.logFormat !== 'json') logging.format = state.logFormat;

  // Prune the non-routes sections; routes needs special handling because
  // `route.enabled: false` is a meaningful value that prune() would strip.
  const pruned = (prune({ tun, socks5, autoroutes, logging }) ?? {}) as Record<string, YamlValue>;
  const routes = state.routes
    .filter(r => r.destination.trim())
    .map(r => {
      const entry: Record<string, YamlValue> = {
        destination: r.destination.trim(),
        enabled: r.enabled,
      };
      if (r.comment.trim()) entry.comment = r.comment.trim();
      return entry;
    });
  if (routes.length > 0) pruned.routes = routes;

  // Admin HTTP interface. Mutiauk defaults it to enabled on
  // 127.0.0.1:48088, so only emit deltas: `enabled: false` when disabled, or a
  // custom loopback `listen`. Built outside prune() because `enabled: false`
  // is meaningful and prune() strips falsey values.
  const admin: Record<string, YamlValue> = {};
  if (!state.adminEnabled) {
    admin.enabled = false;
  } else if (state.adminListen.trim() && state.adminListen.trim() !== ENTRY_DEFAULT_ADMIN_LISTEN) {
    admin.listen = state.adminListen.trim();
  }
  if (Object.keys(admin).length > 0) pruned.admin = admin;

  const header = [
    '# Mutiauk configuration',
    `# Generated by Muti Metroo Manager wizard on ${new Date().toISOString().slice(0, 10)}`,
    '# Run: sudo mutiauk daemon start -c /etc/mutiauk/config.yaml',
  ];

  // tun is always the first section, so the first `  name:` line is tun.name.
  // The emitter has no comment support, so annotate that one line here: on
  // macOS the kernel ignores the requested name and assigns the next free utunN.
  const body = emitObject(pruned, '');
  const nameIdx = body.findIndex(l => l.startsWith('  name: '));
  if (nameIdx !== -1) {
    body[nameIdx] += '  # macOS ignores this — the kernel assigns the next free utunN (e.g. utun4)';
  }
  return [...header, '', ...body, ''].join('\n');
}
