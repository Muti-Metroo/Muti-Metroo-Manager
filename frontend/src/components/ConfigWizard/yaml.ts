import type { WizardState } from './state';
import { transportHasHttpPath } from '../../api/types';
import { emitObject, prune } from '../../util/yamlEmit';
import type { YamlValue } from '../../util/yamlEmit';

export function buildConfigYaml(state: WizardState): string {
  const hasHttpPath = transportHasHttpPath(state.listenerTransport);

  const agent: Record<string, YamlValue> = {
    id: 'auto',
    display_name: state.displayName.trim(),
    data_dir: state.dataDir.trim(),
    log_level: state.logLevel,
  };

  const tls: Record<string, YamlValue> = {};
  if (state.tlsMode === 'strict') {
    if (state.caPem.trim()) tls.ca_pem = state.caPem.trim() + '\n';
    if (state.agentCertPem.trim()) tls.cert_pem = state.agentCertPem.trim() + '\n';
    if (state.agentKeyPem.trim()) tls.key_pem = state.agentKeyPem.trim() + '\n';
    if (state.tlsMtls) tls.mtls = true;
    if (state.tlsStrict) tls.strict = true;
  }

  const management: Record<string, YamlValue> = {};
  if (state.mgmtMode === 'public_only' || state.mgmtMode === 'operator') {
    if (state.mgmtPublicKey.trim())
      management.public_key = state.mgmtPublicKey.trim().toLowerCase();
    if (state.mgmtSigningPublicKey.trim())
      management.signing_public_key = state.mgmtSigningPublicKey.trim().toLowerCase();
  }
  if (state.mgmtMode === 'operator') {
    if (state.mgmtPrivateKey.trim())
      management.private_key = state.mgmtPrivateKey.trim().toLowerCase();
    if (state.mgmtSigningPrivateKey.trim())
      management.signing_private_key = state.mgmtSigningPrivateKey.trim().toLowerCase();
  }

  const listeners: YamlValue[] = [];
  if (state.listenerEnabled) {
    const listenPath = state.listenPath.trim();
    const listener: Record<string, YamlValue> = {
      transport: state.listenerTransport,
      address: state.listenAddress.trim(),
    };
    if (hasHttpPath) {
      if (listenPath) listener.path = listenPath;
      if (state.listenPlaintext) listener.plaintext = true;
    }
    // Emit `advertise:` only when the operator has supplied a public
    // address. Empty address means "I haven't decided" — better to
    // skip the block than ship a broken default the agent would reject.
    const advertiseAddress = state.advertiseAddress.trim();
    if (state.advertiseEnabled && advertiseAddress) {
      const advertise: Record<string, YamlValue> = { address: advertiseAddress };
      // Path defaults to listener.path on the agent side, so only emit
      // it when h2/ws *and* the listen path is non-empty (so operators
      // editing the YAML later see what's being advertised).
      if (hasHttpPath && listenPath) advertise.path = listenPath;
      listener.advertise = advertise;
    }
    listeners.push(listener);
  }

  const peers: YamlValue[] = state.peers
    .filter(p => p.address.trim())
    .map(p => {
      const entry: Record<string, YamlValue> = {
        transport: p.transport,
        address: p.address.trim(),
      };
      if (p.expectedId.trim()) entry.id = p.expectedId.trim().toLowerCase();
      if (transportHasHttpPath(p.transport) && p.path.trim()) entry.path = p.path.trim();
      return entry;
    });

  const socks5: Record<string, YamlValue> = state.socks5Enabled
    ? { enabled: true, address: state.socks5Address.trim() }
    : {};

  const exit: Record<string, YamlValue> = state.exitEnabled
    ? {
        enabled: true,
        routes: state.exitRoutes.map(r => r.trim()).filter(Boolean),
      }
    : {};

  const http: Record<string, YamlValue> = {};
  if (state.httpEnabled) {
    http.enabled = true;
    http.address = state.httpAddress.trim();
    if (state.httpTokenHash.trim()) http.token_hash = state.httpTokenHash.trim();
  }

  const shell: Record<string, YamlValue> = {};
  if (state.shellEnabled) {
    shell.enabled = true;
    shell.whitelist = state.shellWhitelist.length ? state.shellWhitelist : ['*'];
  }

  const fileTransfer: Record<string, YamlValue> = {};
  if (state.fileTransferEnabled) {
    fileTransfer.enabled = true;
    fileTransfer.allowed_paths = state.fileTransferAllowedPaths.length
      ? state.fileTransferAllowedPaths
      : ['*'];
  }

  const raw: Record<string, YamlValue> = {
    agent,
    tls,
    management,
    listeners,
    peers,
    socks5,
    exit,
    http,
    shell,
    file_transfer: fileTransfer,
  };

  const pruned = (prune(raw) ?? {}) as Record<string, YamlValue>;

  const header = [
    '# Muti Metroo agent configuration',
    `# Generated by Muti Metroo Manager wizard on ${new Date().toISOString().slice(0, 10)}`,
    '# Review before deploying; agent identity keys are generated on first run.',
  ];

  const tokenNote =
    state.httpEnabled && !state.httpTokenHash.trim()
      ? [
          '',
          '# NOTE: HTTP API is enabled without authentication. Generate a bcrypt token hash',
          '#       with `muti-metroo hash` and paste it into http.token_hash before shipping.',
        ]
      : [];

  const privKeyNote =
    state.mgmtMode === 'operator' &&
    (state.mgmtPrivateKey.trim() || state.mgmtSigningPrivateKey.trim())
      ? [
          '',
          '# WARNING: This config includes management PRIVATE keys (operator node).',
          '#          The signing private key authorises shell, file transfer, and',
          '#          dynamic mutation requests — distribute only to trusted hosts.',
        ]
      : [];

  const body = emitObject(pruned, '');
  return [...header, ...tokenNote, ...privKeyNote, '', ...body, ''].join('\n');
}
